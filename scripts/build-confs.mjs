// Builds migrations/0002_confs.sql from a local clone of github.com/ccfddl/ccf-deadlines (MIT).
//   git clone --depth 1 https://github.com/ccfddl/ccf-deadlines /tmp/ccf
//   node scripts/build-confs.mjs /tmp/ccf [migrations/0002_confs.sql]
// Re-run with a new output file (e.g. migrations/0005_confs_refresh.sql) to refresh: it upserts.
import fs from 'node:fs';
import path from 'node:path';
import * as yaml from 'js-yaml';

const [root, out = 'migrations/0002_confs.sql'] = process.argv.slice(2);
if (!root) { console.error('usage: node scripts/build-confs.mjs <ccf-deadlines dir> [out.sql]'); process.exit(1); }

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
  d.isDirectory() ? walk(path.join(dir, d.name)) : d.name.endsWith('.yml') ? [path.join(dir, d.name)] : []);

const rates = new Map();
for (const f of walk(path.join(root, 'accept_rates'))) {
  for (const c of yaml.load(fs.readFileSync(f, 'utf8')) || []) {
    const list = (c.accept_rates || []).filter((r) => r.rate).map((r) => ({ year: r.year, submitted: r.submitted, accepted: r.accepted, rate: Math.round(r.rate * 1000) / 1000 }));
    if (list.length) rates.set(String(c.title).toLowerCase(), list.slice(-4));
  }
}

const q = (v) => v == null || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const rows = [];
const seen = new Set();
for (const f of walk(path.join(root, 'conference'))) {
  if (f.endsWith('types.yml')) continue;
  for (const c of yaml.load(fs.readFileSync(f, 'utf8')) || []) {
    if (!c?.title) continue;
    const key = String(c.dblp || c.title).toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    const editions = (c.confs || []).slice(-3).map((e) => ({
      year: e.year, link: e.link, date: e.date, place: e.place, timezone: e.timezone,
      timeline: (e.timeline || []).map((t) => Object.fromEntries(Object.entries(t).filter(([, v]) => v && v !== 'TBD'))),
    }));
    const core = c.rank?.core && c.rank.core !== 'N' ? String(c.rank.core) : null;
    const ccf = c.rank?.ccf && c.rank.ccf !== 'N' ? String(c.rank.ccf) : null;
    rows.push(`INSERT INTO confs (key, title, description, sub, core, ccf, dblp, editions, accept) VALUES (${[
      q(key), q(c.title), q(c.description), q(c.sub), q(core), q(ccf), q(c.dblp),
      q(JSON.stringify(editions)), q(rates.has(String(c.title).toLowerCase()) ? JSON.stringify(rates.get(String(c.title).toLowerCase())) : null),
    ].join(', ')}) ON CONFLICT (key) DO UPDATE SET title = excluded.title, description = excluded.description, sub = excluded.sub,
  core = excluded.core, ccf = excluded.ccf, editions = excluded.editions, accept = excluded.accept;`);
  }
}
fs.writeFileSync(out, '-- Generated by scripts/build-confs.mjs from ccfddl/ccf-deadlines (MIT). Do not edit by hand.\n' + rows.join('\n') + '\n');
console.log(`wrote ${rows.length} conferences to ${out}`);
